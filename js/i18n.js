  /* 主题名/主题组名专用翻译：独立词典，避免与用户数据（人物名等）误撞 */
  trTheme(text) {
    if (this.lang !== 'en' || text == null) return text;
    return this.dict.theme[text] || text;
  },

  tr(text) {
    if (this.lang !== 'en') return text;
    if (text == null) return text;
    if (text in this.dict.en) return this.dict.en[text];
    // 去除首尾 emoji/空白后再精确查（如「📤 只读分享页（单文件 HTML）」）
    const stripped = String(text).replace(/^[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\s]+|[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\s]+$/gu, '').trim();
    if (stripped && stripped !== text && stripped in this.dict.en) return this.dict.en[stripped];
    // 数字/符号与中文混排：按连续中文段分段查表，未收录段保持原文
    return String(text).split(/([\u4e00-\u9fff]+)/).map(seg =>
      (seg in this.dict.en ? this.dict.en[seg] : seg)
    ).join('');
  },

  /* HTML 级翻译管道：翻译文本节点与 placeholder/title/aria-label 属性，
     用于动态生成的弹窗/面板 HTML（未收录词条保持中文，逐步扩充） */
  trHtml(html) {
    if (this.lang !== 'en' || html == null) return html;
    return String(html)
      .replace(/(placeholder|title|aria-label)="([^"]*)"/g, (m, attr, val) => `${attr}="${this.tr(val)}"`)
      .replace(/>([^<>]+)</g, (m, text) => `>${this.tr(text)}<`);
  },

  /* 静态文案替换：data-i18n 标记元素。
     文本替换仅作用于「纯文本子节点」（完整等于 key），保留 <i> 等图标子元素；
     属性替换用 data-i18n-attr="placeholder|title" 指定 */
  applyDom(root) {
    if (this.lang !== 'en') return;
    const els = (root || document).querySelectorAll('[data-i18n]');
    els.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = this.dict.en[key];
      if (val == null) return;
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) el.setAttribute(attr, val);
      // attr 与文本可同时存在：设置属性后继续替换文本节点
      el.childNodes.forEach(n => {
        if (n.nodeType !== 3) return;
        const txt = n.textContent;
        if (txt.trim() === key) n.textContent = val;
        else if (txt.includes(key)) n.textContent = txt.replace(key, val);
      });
    });
  }
